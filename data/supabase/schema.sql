-- Jalankan file ini di Supabase > SQL Editor.
-- Tabel menyimpan satu rekap untuk setiap desa/kelurahan per bulan.

create table if not exists public.absensi (
    id bigint generated by default as identity primary key,
    desa text not null,
    bulan smallint not null check (bulan between 1 and 12),
    tahun smallint not null check (tahun between 2000 and 2100),
    jumlah_laporan integer not null default 0 check (jumlah_laporan >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint absensi_desa_bulan_tahun_key unique (desa, bulan, tahun)
);

create index if not exists absensi_desa_periode_idx
    on public.absensi (desa, tahun, bulan);

alter table public.absensi enable row level security;

drop policy if exists "Absensi dapat dibaca publik" on public.absensi;
create policy "Absensi dapat dibaca publik"
    on public.absensi
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Absensi dapat ditambah publik" on public.absensi;
create policy "Absensi dapat ditambah publik"
    on public.absensi
    for insert
    to anon, authenticated
    with check (jumlah_laporan >= 0);

drop policy if exists "Absensi dapat diperbarui publik" on public.absensi;
create policy "Absensi dapat diperbarui publik"
    on public.absensi
    for update
    to anon, authenticated
    using (true)
    with check (jumlah_laporan >= 0);

